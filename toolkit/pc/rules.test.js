// Tests for the chat rules (run in the build: node rules.test.js)
const assert = require('assert');
const { ChatRules, chatFromLog, serverFromLog, splitSender } = require('./rules.js');
const r = new ChatRules({ blockedWords: ['badword', 'noob'] });
const flag = (t, s) => new ChatRules({ blockedWords: ['badword', 'noob'] }).check(t, Date.now(), s);
assert.strictEqual(chatFromLog('[12:01:02] [Render thread/INFO]: [System] [CHAT] §7[VIP] §fSteve§7: hi'), '[VIP] Steve: hi');
assert.strictEqual(serverFromLog('[12:00:00] [Render thread/INFO]: Connecting to play.example.net, 25565'), 'play.example.net');
assert.deepStrictEqual(splitSender('[VIP] Steve: hello there'), { player: 'Steve', message: 'hello there' });
assert.deepStrictEqual(splitSender('<Alex> yo'), { player: 'Alex', message: 'yo' });
assert.deepStrictEqual(splitSender('Owner | Notch » welcome'), { player: 'Notch', message: 'welcome' });
assert.strictEqual(splitSender('Welcome to the server!').player, null);
assert.ok(flag('Steve: join play.coolmc.net now').reasons[0].startsWith('Advertising'));
assert.ok(flag('Steve: join play (dot) coolmc (dot) net').reasons[0].startsWith('Advertising'));
assert.ok(flag('Steve: 192.168.1.5:25565 best server').reasons[0].includes('IP'));
assert.ok(flag('Steve: discord.gg/abc123').reasons[0].includes('Discord'));
assert.strictEqual(flag('Steve: watch my youtube.com/abc'), null);
assert.strictEqual(flag('Steve: our site play.example.net', 'play.example.net'), null);
assert.ok(flag('Bob: you are a n00b').reasons[0].startsWith('Blocked word'));
assert.ok(flag('Bob: b a d w o r d').reasons[0].startsWith('Blocked word'));
assert.strictEqual(flag('Bob: I know nobody here'), null);
assert.ok(flag('Bob: WHY IS EVERYONE SO BAD').reasons.includes('Caps'));
assert.ok(flag('Bob: hiiiiiiiiiii').reasons.includes('Character flood'));
assert.strictEqual(flag('Bob: OK'), null);
assert.strictEqual(flag('Restarting in 5 minutes'), null);
const t = Date.now();
r.check('Spammer: buy stuff', t); r.check('Spammer: buy stuff', t + 1000);
assert.ok(r.check('Spammer: buy stuff', t + 2000).reasons[0].startsWith('Repeated'));
const w = new ChatRules({ watchPlayers: ['Griefer1'], ignorePlayers: ['ModBot'] });
assert.deepStrictEqual(w.check('Griefer1: hello').reasons, ['Watched player']);
assert.strictEqual(w.check('ModBot: join play.x.net'), null);
console.log('chat rules: all tests passed');
